"""README and run report for the generated project (written by code from real data, not by the LLM)."""

from __future__ import annotations

from .digest import endpoint_reqs


def run_report(orch, seconds: float) -> dict:
    m = orch.llm.meter
    rate = orch.llm.s.usd_to_cny
    by_role = {r: {"cache_hit": u.cache_hit, "cache_miss": u.cache_miss, "output": u.output,
                   "reasoning": u.reasoning} for r, u in m.by_role.items()}
    st = orch.state
    return {
        "status": st.status, "seconds": round(seconds, 1),
        "cost": {"cny": round(m.spent_cny, 4), "usd": round(m.spent_cny / rate, 4),
                 "budget_usd": orch.llm.s.budget_usd, "calls": m.calls,
                 "cache_hit_rate": round(m.usage.hit_rate, 3), "tokens_by_role": by_role},
        "phases": st.phases, "agents": st.agents, "test_history": st.test_history,
        "tests": st.tests.summary() if st.tests else "none",
        "traceability": {s: sum(r["status"] == s for r in st.matrix)
                         for s in ("PASS", "FAIL", "UNTESTED", "NOT_IMPLEMENTED")},
        "review_verdict": st.review.get("verdict"), "review_findings": st.review.get("findings", []),
        "conformance": st.conformance, "test_integrity_violations": st.tamper, "notes": st.notes,
    }


def readme(ir: dict, st, report: dict) -> str:
    name = ir["system"].get("name") or "Generated project"
    sel = ir.get("stack", {}).get("selected", {})
    ereq = endpoint_reqs(ir)
    L = [f"# {name}", "",
         ir["system"].get("summary", ""), "",
         "> Generated by **ArchForge** from `Architecture_Documentation.md` + `Architecture_View.md`. "
         "Every design decision that is not literally in the spec is listed in "
         "[docs/spec/assumptions.md](docs/spec/assumptions.md); spec defects found are in "
         "[docs/spec/lint_report.md](docs/spec/lint_report.md).", "",
         "## Run it", "",
         "```bash",
         "npm install          # first time (downloads Electron)",
         "npm start            # desktop app (Electron window)",
         "npm test             # Jest test suite",
         "npm run server       # headless REST API on http://localhost:3000",
         "npm run dist         # build a portable Windows .exe into dist/",
         "docker build -t space-fractions . && docker run -p 3000:3000 space-fractions   # API in a container",
         "```", "",
         "**Admin screen / admin API:** the admin token protects the question bank (ASR-2). Default: "
         "`dev-admin-token`; set your own before starting: `set ADMIN_TOKEN=your-secret` (Windows) or "
         "`export ADMIN_TOKEN=your-secret`. API clients send it in the `x-admin-token` header.", "",
         "## Architecture", "",
         st.plan.get("summary", ""), "",
         "Modular monolith: one module per architecture component, each with its own router/service, talking "
         "through interfaces, inside one process (see lint finding on microservices vs. single deployment).", "",
         "| Component | Folder | Responsibility |", "|---|---|---|"]
    for c in ir["components"]:
        slug = c["name"].replace("Component", "").lower()
        L.append(f"| {c['name']} | `src/components/{slug}/` | {c['responsibility']} |")
    L += ["", "## REST API", "", "Full contract: [openapi.yaml](openapi.yaml).", "",
          "| Endpoint | Origin | Requirements |", "|---|---|---|"]
    for e in ir["api"]["endpoints"]:
        k = f"{e['method']} {e['path']}"
        L.append(f"| `{k}` | {e.get('origin', 'spec')} | {', '.join(ereq.get(k, []))} |")
    sm = ir.get("state_machine") or {}
    if sm:
        L += ["", "## Game state machine", "",
              "; ".join(f"`{t['from']}` --{t['trigger']}--> `{t['to']}`" for t in sm["transitions"]) +
              ". Illegal transitions return HTTP 409."]
    L += ["", "## Stack", ""]
    L += [f"- **{k.replace('_', ' ')}**: {v}" for k, v in sel.items() if k != "out_of_scope"]
    if sel.get("out_of_scope"):
        L.append(f"- **Not used (out of scope for this system's size)**: {', '.join(sel['out_of_scope'])}")
    slo = ir.get("quality", {}).get("slo", {})
    if slo.get("error_budget", {}).get("resolved_value"):
        L.append(f"- SLO note: {slo['slo']['value']} implies an error budget of "
                 f"{slo['error_budget']['resolved_value']} (the spec said {slo['error_budget']['value']}).")
    t = report["traceability"]
    L += ["", "## Quality", "",
          f"- Tests: **{report['tests']}** (Jest + supertest, written from the spec before the code).",
          f"- Traceability: **{t['PASS']} PASS / {t['FAIL']} FAIL / {t['UNTESTED']} UNTESTED / "
          f"{t['NOT_IMPLEMENTED']} NOT IMPLEMENTED**, see [docs/TRACEABILITY.md](docs/TRACEABILITY.md) "
          f"and [traceability_matrix.csv](traceability_matrix.csv).",
          f"- Reviewer verdict: {report.get('review_verdict') or 'n/a'}"
          + (f" ({len(report.get('review_findings') or [])} findings)." if report.get('review_findings') else "."),
          (f"- Plan conformance: {report['conformance'].get('present')}/{report['conformance'].get('planned')} "
           f"planned modules present, {len(report['conformance'].get('scratch_removed', []))} leftover file(s) "
           f"removed, see [docs/CONFORMANCE.md](docs/CONFORMANCE.md)." if report.get("conformance") else
           "- Plan conformance: n/a"),
          (f"- Test integrity: tests/ locked with SHA-256 after the Tester; "
           + (f"**{len(report['test_integrity_violations'])} change(s) by other agents detected and reverted** "
              f"({', '.join(sorted({v['file'] + ' by ' + v['after'] for v in report['test_integrity_violations']}))})."
              if report.get("test_integrity_violations") else "no changes by other agents.")), "",
          "## How this project was generated", "",
          f"- Status: {report['status']}, {report['seconds']:.0f}s, {report['cost']['calls']} LLM calls, "
          f"cost **${report['cost']['usd']:.3f}** (CNY {report['cost']['cny']:.3f}) of the "
          f"${report['cost']['budget_usd']:.2f} budget, cache hit rate {report['cost']['cache_hit_rate']:.0%}.",
          "- Phases: " + ", ".join(f"{p['phase']} ({p['seconds']:.0f}s, CNY {p['cost_cny']:.3f})" for p in report["phases"]),
          "- Test progress: " + " -> ".join(f"{h['passed']}/{h['total']}" for h in report["test_history"]),
          "- Plan: [docs/PLAN.md](docs/PLAN.md)"]
    return "\n".join(L) + "\n"
