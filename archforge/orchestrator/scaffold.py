"""Deterministic scaffold: the files that must be EXACT, not creative.

Written by code, not by the LLM, on purpose:
  package.json      pinned, real dependencies -> the model cannot invent packages
                    (a known supply-chain risk called "package hallucination")
  openapi.yaml      generated from the resolved IR + Architect contract -> the API
                    document always matches what the tests check
  sql/*.sql         generated from the IR tables (incl. the questions table Spec Lint added)
  Dockerfile        headless server mode, pinned base image
  .gitignore, .dockerignore
"""

from __future__ import annotations

import json
import os
import re

import yaml

from .digest import endpoint_reqs

PACKAGE_VERSION = "1.0.0"
DEPENDENCIES = {"express": "4.21.2"}
DEV_DEPENDENCIES = {"jest": "29.7.0", "supertest": "7.0.0", "electron": "33.2.1", "electron-builder": "25.1.8"}


def package_json(ir: dict) -> dict:
    name = re.sub(r"[^a-z0-9]+", "-", (ir["system"].get("name") or "app").lower()).strip("-")
    return {
        "name": name, "version": PACKAGE_VERSION, "private": True,
        "description": f"{ir['system'].get('name')} - generated by ArchForge from the architecture spec",
        "main": "electron/main.js",
        "scripts": {
            "start": "electron .",
            "server": "node src/server.js",
            "test": "jest --runInBand",
            "dist": "electron-builder --win portable",
        },
        "engines": {"node": ">=18"},
        "dependencies": DEPENDENCIES,
        "devDependencies": DEV_DEPENDENCIES,
        "jest": {"testEnvironment": "node", "testMatch": ["**/tests/**/*.test.js"], "testTimeout": 15000},
        "build": {
            "appId": f"com.archforge.{name.replace('-', '')}", "productName": ir["system"].get("name") or name,
            "files": ["electron/**", "public/**", "src/**", "package.json"],
            "win": {"target": "portable", "signAndEditExecutable": False},   # no code-signing toolchain needed
            "npmRebuild": False, "directories": {"output": "dist"},
        },
    }


def openapi(ir: dict, plan: dict) -> str:
    contract = {f"{a['method'].upper()} {a['path']}": a for a in plan.get("api", [])}
    paths: dict = {}
    for e in ir["api"]["endpoints"]:
        key = f"{e['method']} {e['path']}"
        c = contract.get(key, {})
        op = {"summary": e.get("summary") or c.get("response", ""),
              "x-origin": e.get("origin", "spec"),
              "x-requirements": endpoint_reqs(ir).get(key, []),
              "responses": {"200": {"description": c.get("response") or "OK"}}}
        if e.get("derived_from"):
            op["x-derived-from"] = e["derived_from"]
        params = re.findall(r"\{(\w+)\}", e["path"])
        if params:
            op["parameters"] = [{"name": p, "in": "path", "required": True, "schema": {"type": "integer"}}
                                for p in params]
        if e.get("response_schema"):
            op["responses"]["200"]["content"] = {"application/json": {"schema": e["response_schema"]}}
        for err in c.get("errors", []):
            m = re.match(r"\s*(\d{3})\s*(.*)", str(err))
            if m:
                op["responses"][m.group(1)] = {"description": m.group(2) or "error"}
        if e["path"].startswith("/admin"):
            op["security"] = [{"adminToken": []}]
        paths.setdefault(e["path"], {})[e["method"].lower()] = op
    doc = {"openapi": "3.0.0",
           "info": {"title": f"{ir['system'].get('name')} API", "version": PACKAGE_VERSION,
                    "description": "Generated by ArchForge. x-origin: spec = from the documents, "
                                   "derived = added by Spec Lint from the diagrams."},
           "paths": paths,
           "components": {"securitySchemes": {"adminToken": {"type": "apiKey", "in": "header",
                                                             "name": "x-admin-token"}}}}
    return yaml.safe_dump(doc, sort_keys=False, allow_unicode=True)


def sql_files(ir: dict) -> dict[str, str]:
    files: dict[str, list[str]] = {}
    seen = set()
    for t in ir["data"]["tables"]:
        if t["table"] in seen:
            continue
        seen.add(t["table"])
        path = t.get("file") or f"sql/{t['table'].rstrip('s')}_ddl.sql"
        cols = ",\n".join(f"  {c['name']} {c['type']} {c['constraints']}".rstrip() for c in t["columns"])
        files.setdefault(path, []).append(f"-- origin: {t.get('origin', 'spec')}\nCREATE TABLE {t['table']} (\n{cols}\n);")
    return {p: "-- PostgreSQL 14 DDL generated by ArchForge\n" + "\n\n".join(v) + "\n" for p, v in files.items()}


DOCKERFILE = """# Headless server mode (REST API). The desktop app is built with `npm run dist`.
FROM node:18.20-alpine
WORKDIR /app
COPY package*.json ./
RUN npm install --omit=dev --no-audit --no-fund
COPY src ./src
COPY public ./public
ENV PORT=3000
EXPOSE 3000
CMD ["node", "src/server.js"]
"""

GITIGNORE = "node_modules/\ndist/\ncoverage/\ndata/\n.archforge/\n*.log\n"
DOCKERIGNORE = "node_modules\ndist\ncoverage\n.archforge\ntests\n"


def write_scaffold(root: str, ir: dict, plan: dict, spec_dir: str | None = None) -> list[str]:
    files = {
        "package.json": json.dumps(package_json(ir), indent=2) + "\n",
        "openapi.yaml": openapi(ir, plan),
        "Dockerfile": DOCKERFILE,
        ".gitignore": GITIGNORE,
        ".dockerignore": DOCKERIGNORE,
        **sql_files(ir),
    }
    if spec_dir:   # ship the spec analysis with the project
        for name in ("lint_report.md", "assumptions.md", "ir.resolved.json"):
            src = os.path.join(spec_dir, name)
            if os.path.exists(src):
                with open(src, encoding="utf-8") as f:
                    files[f"docs/spec/{name}"] = f.read()
    for rel, content in files.items():
        full = os.path.join(root, rel)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
    return sorted(files)
